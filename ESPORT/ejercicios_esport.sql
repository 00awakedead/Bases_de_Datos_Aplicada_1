SELECT * FROM REGIONES;

--#2
SELECT NOMBRE, ROL, ORIGEN_LORE FROM AGENTES;

--#3
SELECT NICKNAME AS ALIAS_JUGADOR, NOMBRE_REAL AS NOMBRE_COMPLETO, SUELDO_MENSUAL AS SALARIO_USD FROM JUGADORES;

--#4
SELECT NICKNAME, SUELDO_MENSUAL, SUELDO_MENSUAL * 12 AS SUELDO_ANUAL FROM JUGADORES;

--#5
SELECT NOMBRE, TAG, PRESUPUESTO_ANUAL / 1000000 AS PRESUPUESTO_MILLONES FROM  EQUIPOS;

--#6
SELECT ID, KILLS, ASSISTS, DEATHS, (KILLS + ASSISTS) AS PARTICIPACION_OFENSIVA FROM PARTICIPACIONES;


-- WHERE

--#7
SELECT NICKNAME, PAIS_NATAL, SUELDO_MENSUAL FROM JUGADORES WHERE PAIS_NATAL = 'Chile';

--#8
SELECT NICKNAME, EDAD, SUELDO_MENSUAL FROM JUGADORES WHERE SUELDO_MENSUAL > 25000;

--#9
SELECT NOMBRE, AMBIENTACION FROM MAPAS WHERE SITIOS_BOMBA = 3;

--#10
SELECT NICKNAME, EDAD, SUELDO_MENSUAL FROM JUGADORES WHERE EDAD BETWEEN 19 AND 22;

--#11
SELECT NICKNAME, PAIS_NATAL FROM JUGADORES WHERE PAIS_NATAL IN('Brasil', 'Canada', 'Rusia');

--#12
SELECT ROL, ORIGEN_LORE FROM AGENTES WHERE ROL = 'Duelista' OR ROL = 'Iniciador' AND ORIGEN_LORE != 'Desconocido';

--#13
SELECT FASE, ASISTENCIA_PUBLICO FROM PARTIDAS WHERE FASE LIKE '%Final%' AND ASISTENCIA_PUBLICO > 10000;

--#14
SELECT NOMBRE, TAG, PRESUPUESTO_ANUAL FROM EQUIPOS ORDER BY PRESUPUESTO_ANUAL DESC;

--#15
SELECT NICKNAME, EDAD, NOMBRE_REAL FROM JUGADORES ORDER BY EDAD ASC;

--#16
SELECT PAIS_NATAL, NICKNAME, SUELDO_MENSUAL FROM JUGADORES ORDER BY PAIS_NATAL ASC, SUELDO_MENSUAL DESC;

--#17
SELECT * FROM PARTIDAS ORDER BY FECHA_PARTIDA DESC;

--#18
SELECT GANO, JUGADOR_ID, PARTIDA_ID, KILLS, PUNTAJE_COMBATE FROM PARTICIPACIONES WHERE GANO = 'S' ORDER BY PUNTAJE_COMBATE DESC;

--#19
SELECT * FROM PATROCINIOS ORDER BY TIPO_CONTRATO ASC, MONTO_ANUAL DESC;

--#20
SELECT COUNT(*) AS TOTAL_JUGADORES, ROUND(AVG(SUELDO_MENSUAL)) AS SUELDO_PROMEDIO, MIN(SUELDO_MENSUAL) AS SUELDO_MINIMO, MAX(SUELDO_MENSUAL) AS SUELDO_MAXIMO FROM JUGADORES;

--#21
SELECT ROL, COUNT(*) AS AGENTES_POR_ROL FROM AGENTES GROUP BY ROL;

--#22
SELECT PAIS_NATAL, COUNT(*) AS CANTIDAD FROM JUGADORES GROUP BY PAIS_NATAL ORDER BY CANTIDAD DESC;

--#23
SELECT FASE, COUNT(*) AS PARTIDAS_JUGADAS, ROUND(AVG(DURACION_MIN)), SUM(ASISTENCIA_PUBLICO) FROM PARTIDAS GROUP BY FASE;

--#24
SELECT RUBRO, COUNT(*) AS PATROCINADORES_POR_RUBRO FROM PATROCINADORES GROUP BY RUBRO;

--#25
SELECT TIPO_CONTRATO, COUNT(*) AS CANTIDAD_CONTRATO, SUM(MONTO_ANUAL) AS MONTO_TOTAL FROM PATROCINIOS GROUP BY TIPO_CONTRATO ORDER BY MONTO_TOTAL DESC;

--#26
SELECT GANO, COUNT(*) AS CANTIDAD_REGISTRO, ROUND(AVG(KILLS)) AS PROMEDIO_KILLS, ROUND(AVG(PUNTAJE_COMBATE)) AS PROMEDIO_PUNTAJE_COMBATE FROM PARTICIPACIONES GROUP BY GANO;

--#27
SELECT EQUIPO_ID , COUNT(*) AS CANTIDAD_JUGADORES, MIN(SUELDO_MENSUAL) AS SUELDO_MINIMO, MAX(SUELDO_MENSUAL) AS SUELDO_MAXIMO, SUM(SUELDO_MENSUAL) AS SUMA_DE_SUELDOS FROM JUGADORES GROUP BY EQUIPO_ID;

--#28
SELECT e.NOMBRE AS NOMBRE_EQUIPO, e.TAG, e.PRESUPUESTO_ANUAL, r.NOMBRE AS NOMBRE_REGION FROM EQUIPOS e JOIN REGIONES r ON e.REGION_ID = r.ID;

--#29
SELECT NICKNAME, SUELDO_MENSUAL, NOMBRE AS NOMBRE_EQUIPO FROM JUGADORES j JOIN EQUIPOS e ON j.equipo_id = e.id ORDER BY j.SUELDO_MENSUAL DESC;

--#30
SELECT p.ID AS ID_PARTIDA, p.FASE, p.FECHA_PARTIDA, p.DURACION_MIN, m.NOMBRE FROM PARTIDAS p JOIN mapas m ON p.MAPA_ID = m.ID;

--#31
SELECT e.NOMBRE AS NOMBRE_EQUIPO, p.NOMBRE AS NOMBRE_PATROCINADOR, pt.TIPO_CONTRATO, pt.MONTO_ANUAL FROM PATROCINIOS pt JOIN EQUIPOS e ON pt.EQUIPO_ID = e.ID JOIN PATROCINADORES p ON pt.PATROCINADOR_ID = p.ID;

--#32
SELECT j.NICKNAME, e.NOMBRE AS NOMBRE_EQUIPO, r.NOMBRE AS NOMBRE_REGION FROM JUGADORES j JOIN EQUIPOS e ON j.EQUIPO_ID = e.ID JOIN REGIONES r ON e.REGION_ID = r.ID;

--#33
SELECT j.NICKNAME, a.NOMBRE AS NOMBRE_AGENTE, a.ROL, pa.KILLS, pa.PUNTAJE_COMBATE FROM PARTICIPACIONES pa JOIN JUGADORES j ON pa.JUGADOR_ID = j.ID JOIN AGENTES a ON pa.AGENTE_ID = a.ID;

--#34
SELECT j.NICKNAME, pt.FASE, m.NOMBRE, pa.KILLS FROM PARTICIPACIONES pa JOIN JUGADORES j ON pa.JUGADOR_ID = j.ID JOIN PARTIDAS pt;