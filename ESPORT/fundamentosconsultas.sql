-- CONSULTA TODAS LAS COLUMNAS DE MI TABLA Y TRAE TODOS LOS DATOS
SELECT * FROM JUGADORES;


-- SOLO LAS COLUMNAS QUE ME INTERESAN
SELECT NICKNAME, NOMBRE_REAL FROM JUGADORES;


-- OPERACION MATEMATICA
SELECT NICKNAME, EDAD * SUELDO_MENSUAL AS SUELDO_ANUAL_POR_EDAD FROM JUGADORES;


-- FILTRAR CON WHERE
SELECT NICKNAME FROM JUGADORES WHERE EDAD > 23;

SELECT NICKNAME, NOMBRE_REAL FROM JUGADORES WHERE EQUIPO_ID = 6;

SELECT NICKNAME, PAIS_NATAL FROM JUGADORES WHERE PAIS_NATAL = 'Brasil';

-- QUE SEA DE CHILE Y MAYORES DE 21
SELECT * FROM JUGADORES WHERE PAIS_NATAL = 'Chile' AND EDAD > 21;

SELECT * FROM JUGADORES WHERE PAIS_NATAL = 'Chile' OR PAIS_NATAL = 'Brasil' AND EDAD > 21 ORDER BY EDAD DESC;

SELECT * FROM JUGADORES WHERE EDAD BETWEEN 20 AND 22;